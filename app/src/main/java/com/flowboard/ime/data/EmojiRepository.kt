    fun getEmojisForCategory(context: Context, category: EmojiCategory): List<String> {
        return when (category) {
            EmojiCategory.RECENT -> getRecentEmojis(context)
            EmojiCategory.SMILEYS -> SMILEYS_EMOJIS
            EmojiCategory.PEOPLE -> PEOPLE_EMOJIS
            EmojiCategory.ANIMALS -> ANIMALS_EMOJIS
            EmojiCategory.FOOD -> FOOD_EMOJIS
            EmojiCategory.TRAVEL -> TRAVEL_EMOJIS
            EmojiCategory.ACTIVITIES -> ACTIVITIES_EMOJIS
            EmojiCategory.OBJECTS -> OBJECTS_EMOJIS
            EmojiCategory.FLAGS -> FLAGS_EMOJIS
        }
    }

    fun getRecentEmojis(context: Context): List<String> {
        val prefs = context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)
        val raw = prefs.getString(KEY_RECENT_EMOJIS, null) ?: return DEFAULT_POPULAR_EMOJIS
        val list = raw.split(",").filter { it.isNotBlank() }
        return if (list.isEmpty()) DEFAULT_POPULAR_EMOJIS else list
    }

    fun addRecentEmoji(context: Context, emoji: String) {
        if (emoji.isBlank()) return
        val currentRecents = getRecentEmojis(context).toMutableList()
        currentRecents.remove(emoji)
        currentRecents.add(0, emoji)
        if (currentRecents.size > MAX_RECENT_EMOJIS) {
            currentRecents.subList(MAX_RECENT_EMOJIS, currentRecents.size).clear()
        }
        val prefs = context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)
        prefs.edit {
            putString(KEY_RECENT_EMOJIS, currentRecents.joinToString(","))
        }
    }
